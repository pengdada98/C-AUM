    @override
    def compute_loss(self, model, inputs, return_outputs=False, *args, **kwargs):
        sample_ids = inputs.pop("sample_ids", None)

        if getattr(self.finetuning_args, "use_asft_loss", False):
            with torch.no_grad():
                ref_outputs = self.ref_model(
                    input_ids=inputs["input_ids"],
                    attention_mask=inputs.get("attention_mask", None),
                )
                ref_logits = ref_outputs.logits
            outputs = model(**inputs)
            base_loss = self.compute_loss_func(outputs, inputs["labels"], ref_logits)
        else:
            base_loss, outputs = super().compute_loss(model, inputs, return_outputs=True, *args, **kwargs)

        total_loss = base_loss

        if model.training and sample_ids is not None and "labels" in inputs:
            logits = outputs.get("logits") if isinstance(outputs, dict) else outputs[1]
            labels = inputs["labels"]

            shift_logits = logits[..., :-1, :].contiguous()
            shift_labels = labels[..., 1:].contiguous()
            batch_size = shift_logits.size(0)

            per_token_loss = torch.nn.functional.cross_entropy(
                shift_logits.view(-1, shift_logits.size(-1)),
                shift_labels.view(-1),
                ignore_index=-100,
                reduction='none'
            ).view(batch_size, -1)

            penalty_factors = []
            weighted_losses = []

            for i in range(batch_size):
                active_idx = (shift_labels[i] != -100).nonzero(as_tuple=True)[0]
                if len(active_idx) == 0:
                    penalty_factors.append(torch.tensor(0.0, device=logits.device))
                    weighted_losses.append(torch.tensor(0.0, device=logits.device))
                    continue

                last_active_idx = active_idx[-1]
                target_class = shift_labels[i, last_active_idx]
                token_logits = shift_logits[i, last_active_idx]

                logit_true = token_logits[target_class]
                mask = torch.ones_like(token_logits, dtype=torch.bool)
                mask[target_class] = False
                logit_max_false = torch.max(token_logits[mask])

                margin_i = (logit_true - logit_max_false).item()
                s_id = sample_ids[i].item()

                self.aum_tracker[s_id] = self.aum_tracker.get(s_id, 0.0) + margin_i
                current_aum = self.aum_tracker[s_id]

                factor = torch.sigmoid(torch.tensor(current_aum / 5.0)).to(logits.device)
                penalty_factors.append(factor)

                sample_weight = 1.0 + 0.5 * torch.sigmoid(
                    torch.tensor(-current_aum / 10.0) 
                ).to(logits.device)
                
                active_mask = (shift_labels[i] != -100)
                sample_loss = per_token_loss[i][active_mask].mean()
                weighted_losses.append(sample_weight * sample_loss)

            if penalty_factors:
                dynamic_scale = torch.stack(penalty_factors).mean().detach()

                lora_penalty = 0.0
                lora_tensors_count = 0
                for name, param in model.named_parameters():
                    if "lora_A" in name or "lora_B" in name:
                        lora_penalty += torch.norm(param, p=2)
                        lora_tensors_count += 1

                if lora_tensors_count > 0:
                    lora_penalty = lora_penalty / lora_tensors_count

                alpha = 0.0001 
                weighted_base_loss = torch.stack(weighted_losses).mean()
                total_loss = weighted_base_loss + alpha * dynamic_scale * lora_penalty

        return (total_loss, outputs) if return_outputs else total_loss
    
